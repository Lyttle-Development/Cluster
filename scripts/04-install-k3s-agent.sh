#!/usr/bin/env bash
# ==============================================================================
# Step 04: Install K3s Worker / Agent Node
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/common.sh
source "${SCRIPT_DIR}/common.sh"

check_root

# Load environment configuration if present
load_env "${1:-/etc/cluster-node.env}"

K3S_SERVER_URL="${K3S_SERVER_URL:-${SERVER_URL:-}}"
K3S_TOKEN="${K3S_TOKEN:-${TOKEN:-}}"
NODE_IP="${NODE_IP:-$(curl -s https://api.ipify.org || hostname -I | awk '{print $1}')}"

if [[ -z "${K3S_SERVER_URL}" ]]; then
    fatal "K3S_SERVER_URL is not set! Specify the control plane URL (e.g. https://<server-ip>:6443)."
fi

if [[ -z "${K3S_TOKEN}" ]]; then
    fatal "K3S_TOKEN is not set! Provide the cluster token generated by the server node."
fi

info "Starting Step 04: Joining K3s Agent Node to cluster..."
info "Server URL: ${K3S_SERVER_URL}"
info "Agent IP:   ${NODE_IP}"

# 1. Create K3s configuration directory
mkdir -p /etc/rancher/k3s

# 2. Write Agent Configuration
cat <<EOF > /etc/rancher/k3s/config.yaml
server: "${K3S_SERVER_URL}"
token: "${K3S_TOKEN}"
EOF

info "Created /etc/rancher/k3s/config.yaml"

# 3. Run K3s agent installer
info "Executing K3s agent installation..."
curl -sfL https://get.k3s.io | K3S_URL="${K3S_SERVER_URL}" K3S_TOKEN="${K3S_TOKEN}" sh -s - agent

# 4. Wait for k3s-agent systemd service
info "Waiting for k3s-agent service to reach active state..."
for _ in {1..30}; do
    if systemctl is-active --quiet k3s-agent; then
        break
    fi
    sleep 2
done

if ! systemctl is-active --quiet k3s-agent; then
    fatal "k3s-agent failed to start. Check 'journalctl -u k3s-agent -n 50' for details."
fi

# Save node metadata
cat <<EOF > /etc/cluster-node.env
ROLE=agent
NODE_IP=${NODE_IP}
K3S_SERVER_URL=${K3S_SERVER_URL}
EOF
chmod 600 /etc/cluster-node.env

success "Step 04 completed: K3s Agent successfully joined the cluster!"
